# Clase con funciones matematicas básicas

class Basicas():
    def suma(a: int, b: int) -> int:
        """
        Suma dos números.

        Args:
            a (int): Primer número.
            b (int): Segundo número.

        Returns:
            int: La suma de a y b.
        """
        return a + b

    def resta(a: int, b: int) -> int:
        """
        Resta dos números.
        Args:
            a (int): Primer número.
            b (int): Segundo número.

        Returns:
            int: La resta de a y b.
        """
        return a - b
